"""
SBI runner: single-round amortized Neural Posterior Estimation (NPE).

Implements the ``mode='sbi'`` branch of ``inference_core.run_inference``
(Phase B of plans/monte-carlo-sbi-implementation-plan.md). Trains a
normalizing-flow posterior estimator q(theta | x) on a prior-predictive
training set generated by ``MCMCRunner.generate_sbi_dataset``, then
conditions on the observed data to draw posterior samples.

Scientific conventions (do not change silently)
-----------------------------------------------
- **Theta space**: training and sampling happen in the *raw* parameter
  space of ``config.param_space``, in the order of its keys — identical
  to MCMC. Parameters named ``log10_*`` are ALREADY log10 quantities
  (e.g. log10 of viscosity in Pa·s); no additional log transform is
  applied here. ``Tb_K`` is in kelvin, ``alpha`` is dimensionless.
- **Prior**: ``BoxUniform`` built directly from ``config.param_space``
  bounds. This provably matches ``MCMCRunner._build_prior``'s
  ``scipy.stats.uniform(loc=low, scale=high-low)`` for
  ``prior_type='uniform'``. Non-uniform priors raise
  ``NotImplementedError`` (none of the current presets use them).
- **Imaginary-part convention**: training sets are generated with
  ``imag_convention='abs'`` — the x column for the Im(k2) observable
  stores |Im k2|, matching the MCMC likelihood and GUI convention.
  Conditioning values are likewise |Im k2|.
- **Flow density is NOT a likelihood**: the flow's log q(theta | x_obs)
  is a posterior-density estimate. It is stored in
  ``metadata['flow_log_prob']`` only. ``InferenceResult.log_likelihoods``
  holds the recomputed Gaussian chi^2 log-likelihood evaluated with the
  same ``MCMCRunner`` likelihood used for MCMC, so downstream consumers
  (e.g. ``get_best_fit``) see a true likelihood.
- **Weights**: SBI posterior draws are unweighted; ``weights=None``.

Lazy imports: this module imports without torch/sbi installed; an
informative ImportError is raised only when a method that needs them
runs. ``load_artifact`` does not require a structure cache.

Author: PlanetProfile Team
Date: 2026-07-04
"""
