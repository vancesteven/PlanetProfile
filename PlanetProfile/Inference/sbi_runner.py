    def _x_obs_vector(self, x_obs: Dict[str, float]) -> np.ndarray:
        """Map an {observable_name: value} dict onto the trained x order.

        Accepts 'Im_k2' and 'abs_Im_k2' as aliases for the imaginary-k2
        channel; with imag_convention='abs' the value is |Im k2| (abs()
        is applied defensively so a signed input cannot silently condition
        the flow outside its training support).
        """
        vec = []
        for name in self.obs_names:
            if name in x_obs:
                val = float(x_obs[name])
            elif name in _IM_K2_ALIASES:
                alias = next((a for a in _IM_K2_ALIASES if a != name and a in x_obs), None)
                if alias is None:
                    raise KeyError(
                        f"x_obs missing observable '{name}' "
                        f"(aliases tried: {_IM_K2_ALIASES}); got keys {list(x_obs)}"
                    )
                val = float(x_obs[alias])
            else:
                raise KeyError(
                    f"x_obs missing observable '{name}'; got keys {list(x_obs)}"
                )
            # Fold EVERY channel trained as 'abs' (defensive: a signed
            # input must not condition the flow off its training manifold).
            # channel_conventions covers Im_k2 AND Im_h2 (and any future
            # abs channel); the alias check remains as fallback for
            # artifacts predating channel_conventions (2026-07-17), which
            # only had k2 aliases and a global imag_convention.
            # (Gap surfaced by Machine B 2026-07-18: Im_h2 was trained
            # folded but never folded here.)
            conv = getattr(self, 'channel_conventions', None) or {}
            _abs_fallback = _IM_K2_ALIASES + ('Im_h2', 'abs_Im_h2')
            if conv.get(name) == 'abs' or (
                    name not in conv and name in _abs_fallback
                    and self.imag_convention == 'abs'):
                val = abs(val)
            vec.append(val)
        return np.asarray(vec, dtype=np.float64)

    def sample_posterior(
        self,
        x_obs: Dict[str, float],
        n_samples: int = 10000,
        seed: Optional[int] = None,
        reject_outside_prior: bool = True,
    ) -> np.ndarray:
        """Draw posterior samples conditioned on observed data.

        Args:
            x_obs: Dict keyed by observable names (e.g.
                ``{'Re_k2': 0.608, 'abs_Im_k2': 0.135}``; 'Im_k2' is
                accepted as an alias, abs() is applied for the 'abs'
                convention). Values in the same units as the training x.
            n_samples: Number of posterior draws.
            seed: torch.manual_seed value for reproducible draws
                (None = do not reseed).
            reject_outside_prior: If True (default), sbi's DirectPosterior
                rejects proposals outside the prior box — the public
                contract: returned draws are valid posterior samples. Pass
                False ONLY for diagnostic sweeps at far-out-of-distribution
                x (e.g. validate_sbi's limits grid, where the NSF spline
                asserts under rejection at heavy-tailed x and the gate's own
                containment check measures the leakage honestly instead).

        Returns:
            (n_samples, D) numpy array in raw theta space,
            columns in ``param_names`` order.
        """
        torch, _ = _import_torch_sbi()

        if self._posterior is None:
            raise RuntimeError(
                "No trained posterior available. Call train()/run() or load_artifact() first."
            )

        # Conditioning vector is deterministic given x_obs — build it once, so
        # every resample attempt reuses the identical x (retries perturb only
        # the RNG, never the conditioning).
        x_vec = self._x_obs_vector(x_obs)
        x_t = torch.as_tensor(x_vec, dtype=torch.float32)

        # nflows spline-inversion resample guard (see _is_nflows_spline_assertion).
        # Scoped to the reject_outside_prior=True public/GUI contract path: the
        # diagnostic reject_outside_prior=False sweeps (validate_sbi limits grid)
        # deliberately drive x off-manifold and let the assert / containment
        # measure leakage honestly, so we must NOT silently resample there.
        guard_spline = bool(reject_outside_prior)
        base_seed = seed if seed is not None else 0
        for attempt in range(_MAX_SPLINE_RESAMPLE if guard_spline else 1):
            if seed is not None or attempt > 0:
                # Reseed on the caller's seed (reproducible) and, on retry, walk
                # to an independent RNG state for a genuinely fresh noise draw.
                torch.manual_seed(base_seed + attempt * _SPLINE_RESEED_STRIDE)
            try:
                samples = self._posterior.sample(
                    (int(n_samples),), x=x_t, show_progress_bars=False,
                    reject_outside_prior=reject_outside_prior,
                )
                break
            except AssertionError as exc:
                if not (guard_spline and _is_nflows_spline_assertion(exc)):
                    raise
                log.warning(
                    "nflows spline-inversion discriminant assert on posterior "
                    "sample (attempt %d/%d, n_samples=%d) — floating-point "
                    "roundoff on a bin edge; resampling with fresh RNG.",
                    attempt + 1, _MAX_SPLINE_RESAMPLE, int(n_samples),
                )
        else:
            # Exhausted every independent noise draw — this is not roundoff.
            raise RuntimeError(
                f"nflows spline inversion asserted on all "
                f"{_MAX_SPLINE_RESAMPLE} independent resample attempts at this "
                f"conditioning x — the flow is failing systematically here, not "
                f"from float roundoff. Do not silently accept these draws; "
                f"inspect the conditioning values (x_obs={x_obs})."
            )
        return samples.detach().cpu().numpy().astype(np.float64)

