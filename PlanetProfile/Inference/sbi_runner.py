    def save_artifact(self, path) -> None:
        """Save the trained posterior + provenance to a self-describing .pt.

        Schema (version 1) — dict written with torch.save:
            schema_version, posterior (DirectPosterior, pickled),
            prior_spec, param_names, param_labels, param_units,
            param_bounds, obs_names, imag_convention, channel_conventions,
            theta_norm, x_norm,
            density_estimator, config_hash, bodyname, git_sha, seed,
            n_train_effective, rejection_stats, sbi_version, torch_version,
            created_utc.

        Args:
            path: Output .pt path (parent directories are created).
        """
        torch, sbi_pkg = _import_torch_sbi()

        if self._posterior is None:
            raise RuntimeError("No trained posterior to save. Call train() first.")

        lows, highs = self._param_bounds()
        artifact = {
            'schema_version': SBI_ARTIFACT_SCHEMA_VERSION,
            'posterior': self._posterior,
            'prior_spec': self._prior_spec(),
            'param_names': list(self.param_names),
            'param_labels': list(self.param_labels),
            'param_units': list(self.param_units),
            'param_bounds': [[lo, hi] for lo, hi in zip(lows, highs)],
            'obs_names': list(self.obs_names),
            'imag_convention': self.imag_convention,
            # Per-channel Im convention (additive, schema v1 compatible):
            # 'signed' for Bind_ measurement-space channels, the global
            # imag_convention for k2/h2 Im channels. Absent-key readers fall
            # back to the global imag_convention (old artifacts, no Bind_).
            'channel_conventions': self._channel_conventions(),
            'theta_norm': self._train_info.get('theta_norm'),
            'x_norm': self._train_info.get('x_norm'),
            'density_estimator': self._train_info.get('density_estimator'),
            'config_hash': self.config.generate_hash(),
            'bodyname': self.config.bodyname,
            'git_sha': _git_short_sha(),
            'seed': self._train_info.get('seed'),
            'n_train_effective': self._train_info.get('n_train_effective'),
            'rejection_stats': self._train_info.get('rejection_stats'),
            'sbi_version': sbi_pkg.__version__,
            'torch_version': torch.__version__,
            'created_utc': datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ'),
        }
        path = Path(path)
        path.parent.mkdir(parents=True, exist_ok=True)
        torch.save(artifact, path)
        log.info(f"SBI artifact saved: {path}")

    @staticmethod
    def _load_artifact_dict(path, validated_version_pairs=None) -> Dict[str, Any]:
        """torch.load an artifact dict with schema/version checks.

        Args:
            path: Artifact .pt path.
            validated_version_pairs: Optional iterable of
                ``(pkg_name, saved_version, installed_version)`` triples for
                which cross-version sampling has been gate-validated on this
                machine (see sbi_artifacts/INDEX.md). A matching mismatch is
                logged at INFO instead of raising the loud RuntimeWarning.
        """
        torch, sbi_pkg = _import_torch_sbi()
        validated = {tuple(t) for t in (validated_version_pairs or ())}

        def _norm(v):
            # Strip pip local build suffixes ('2.8.0+cpu' -> '2.8.0'): the
            # CPU wheel on cloud hosts is the same release as the validated
            # '2.8.0'; a genuinely different release still mismatches.
            return v.split('+')[0] if isinstance(v, str) else v

        path = Path(path)
        if not path.exists():
            raise FileNotFoundError(f"SBI artifact not found: {path}")
        # weights_only=False: the artifact pickles a full DirectPosterior
        # (schema v1). Only load artifacts from trusted sources.
        artifact = torch.load(path, map_location='cpu', weights_only=False)
        if not isinstance(artifact, dict) or 'schema_version' not in artifact:
            raise ValueError(f"Not a recognized SBI artifact (no schema_version): {path}")
        if artifact['schema_version'] != SBI_ARTIFACT_SCHEMA_VERSION:
            raise ValueError(
                f"SBI artifact schema_version {artifact['schema_version']} "
                f"is not supported (expected {SBI_ARTIFACT_SCHEMA_VERSION}): {path}"
            )

        # Loud version-mismatch warnings: pickled flow objects are not
        # guaranteed portable across sbi/torch versions.
        for pkg_name, installed, saved in (
            ('sbi', sbi_pkg.__version__, artifact.get('sbi_version')),
            ('torch', torch.__version__, artifact.get('torch_version')),
        ):
            if saved is not None and _norm(saved) != _norm(installed):
                if (pkg_name, _norm(saved), _norm(installed)) in validated:
                    log.info(
                        f"SBI artifact {path.name}: {pkg_name} {saved} -> "
                        f"{installed} mismatch is gate-validated on this "
                        f"machine (see sbi_artifacts/INDEX.md)."
                    )
                    continue
                msg = (
                    f"SBI artifact {path.name} was saved with {pkg_name} "
                    f"{saved} but {pkg_name} {installed} is installed. "
                    f"Pickled posterior objects may misbehave across versions "
                    f"— validate posterior draws before scientific use."
                )
                warnings.warn(msg, RuntimeWarning, stacklevel=3)
                log.warning(msg)
        return artifact

    @classmethod
    def load_artifact(cls, path, validated_version_pairs=None) -> 'SBIRunner':
        """Load a trained artifact for sampling only (no config, no cache).

        The returned object supports ``sample_posterior`` and exposes
        ``param_names`` / ``param_labels`` / ``param_units`` /
        ``obs_names`` / ``imag_convention`` / ``artifact_meta``, which is
        what the AmortizedInference GUI page consumes. It has no
        InferenceConfig and cannot ``run()`` or ``train()``.

        Args:
            path: Path to a .pt artifact written by save_artifact.

        Returns:
            SBIRunner instance in artifact-only mode.
        """
        artifact = cls._load_artifact_dict(
            path, validated_version_pairs=validated_version_pairs)

        obj = cls.__new__(cls)  # bypass __init__ (no config available)
        obj.config = None
        obj.param_names = list(artifact['param_names'])
        obj.param_labels = list(artifact['param_labels'])
        obj.param_units = list(artifact['param_units'])
        obj.obs_names = list(artifact['obs_names'])
        obj.imag_convention = artifact['imag_convention']
        # Per-channel Im conventions (empty for pre-v2 artifacts). Consumers
        # must NOT abs-fold a channel marked 'signed' (e.g. Bind_ family).
        obj.channel_conventions = dict(artifact.get('channel_conventions') or {})
        obj._mcmc_runner = None
        obj._posterior = artifact['posterior']
        obj._train_info = {
            'density_estimator': artifact.get('density_estimator'),
            'seed': artifact.get('seed'),
            'n_train_effective': artifact.get('n_train_effective'),
            'rejection_stats': artifact.get('rejection_stats'),
            'theta_norm': artifact.get('theta_norm'),
            'x_norm': artifact.get('x_norm'),
        }
        obj.artifact_meta = {
            k: v for k, v in artifact.items() if k != 'posterior'
        }
        log.info(
            f"SBI artifact loaded: {Path(path).name} "
            f"(body={artifact.get('bodyname')}, "
            f"n_train={artifact.get('n_train_effective')}, "
            f"sbi={artifact.get('sbi_version')})"
        )
        return obj

