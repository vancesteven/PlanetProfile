    def _find_matching_artifact(self, config_hash: str) -> Optional[Path]:
        """Return the first artifact in sbi_artifacts/ whose config_hash matches."""
        explicit = self.config.sampler_settings.get('sbi_artifact_path')
        candidates = []
        if explicit:
            candidates.append(Path(explicit))
        if SBI_ARTIFACTS_DIR.is_dir():
            candidates.extend(sorted(SBI_ARTIFACTS_DIR.glob('*.pt')))
        for cand in candidates:
            if not cand.exists():
                continue
            try:
                artifact = self._load_artifact_dict(cand)
            except Exception as e:
                log.debug(f"Skipping unreadable SBI artifact {cand}: {e}")
                continue
            if artifact.get('config_hash') == config_hash:
                return cand
        return None

    def _default_artifact_path(self, config_hash: str) -> Path:
        """Default save location: sbi_artifacts/<body>_<hash>_posterior.pt."""
        explicit = self.config.sampler_settings.get('sbi_artifact_path')
        if explicit:
            return Path(explicit)
        return SBI_ARTIFACTS_DIR / (
            f"{self.config.bodyname.lower()}_{config_hash}_posterior.pt"
        )

    def run(self, progress_callback: Optional[Callable] = None):
        """Run the full SBI pipeline and return an InferenceResult.

        Steps:
          1. Reuse a trained artifact from ``sbi_artifacts/`` if one exists
             whose ``config_hash`` matches this config; otherwise generate
             ``sampler_settings['num_simulations']`` training simulations,
             train the flow, and save a new artifact.
          2. Condition on the central values of ``config.observables``
             (|Im k2| convention for the imaginary channel) and draw
             ``sampler_settings['n_posterior_samples']`` posterior samples.
          3. Recompute per-sample k2, CMR2, ocean/ice thicknesses, and a
             heating subset with the same MCMCRunner forward-model calls
             the MCMC path uses (no duplicated physics).
          4. Evaluate the Gaussian chi^2 log-likelihood for every sample
             with ``MCMCRunner``'s likelihood — this fills
             ``InferenceResult.log_likelihoods``. The flow's own log
             density (an amortized *posterior* estimate, NOT a likelihood)
             is stored in ``metadata['flow_log_prob']``.

        Args:
            progress_callback: Optional callable receiving a dict with
                keys iteration, n_total, n_samples (contract of
                ``inference_core.run_inference``).

        Returns:
            InferenceResult with unweighted posterior samples
            (``weights=None``).
        """
        from .inference_core import InferenceResult

        torch, sbi_pkg = _import_torch_sbi()

        settings = self.config.sampler_settings
        num_simulations = int(settings.get('num_simulations', 10000))
        n_posterior_samples = int(settings.get('n_posterior_samples', 10000))
        density_estimator = settings.get('density_estimator', 'maf')
        seed = int(self.config.random_state)
        config_hash = self.config.generate_hash()

        n_phases = 4  # dataset+train, sample, recompute, likelihood

        def _progress(phase: int, n_samples_now: int = 0):
            if progress_callback is not None:
                try:
                    progress_callback({
                        'iteration': phase,
                        'n_total': n_phases,
                        'n_samples': n_samples_now,
                    })
                except Exception:
                    pass

        t0 = time.time()
        log.info(f"Starting SBI (NPE) inference for {self.config.bodyname} "
                 f"({len(self.param_names)}D): {self.param_names}")
        log.info(f"Observables: {self.obs_names} (imag_convention="
                 f"'{self.imag_convention}')")

        # --- Step 1: artifact reuse or train --------------------------------
        rejection_stats: Optional[Dict[str, Any]] = None
        reused = False
        artifact_path = self._find_matching_artifact(config_hash)
        if artifact_path is not None:
            log.info(f"Reusing SBI artifact with matching config hash: {artifact_path}")
            artifact = self._load_artifact_dict(artifact_path)
            self._posterior = artifact['posterior']
            self._train_info = {
                'density_estimator': artifact.get('density_estimator'),
                'seed': artifact.get('seed'),
                'n_train_effective': artifact.get('n_train_effective'),
                'rejection_stats': artifact.get('rejection_stats'),
                'theta_norm': artifact.get('theta_norm'),
                'x_norm': artifact.get('x_norm'),
            }
            rejection_stats = artifact.get('rejection_stats')
            reused = True
        else:
            theta_train, x_train, rejection_stats = self.generate_training_set(
                num_simulations, seed=seed
            )
            if rejection_stats.get('rejection_rate', 0.0) > 0.20:
                # Plan-doc gate: stop and surface, do not train on a
                # significantly truncated support.
                raise RuntimeError(
                    f"SBI training-set rejection rate "
                    f"{rejection_stats['rejection_rate']:.1%} exceeds 20% "
                    f"({rejection_stats}). Inspect the prior/support guard "
                    f"before training — do not tune this check to pass."
                )
            self.train(
                theta_train, x_train, seed=seed,
                density_estimator=density_estimator,
            )
            self._train_info['rejection_stats'] = rejection_stats
            artifact_path = self._default_artifact_path(config_hash)
            self.save_artifact(artifact_path)
        _progress(1)

        # --- Steps 2-4: condition, recompute, package ------------------------
        x_obs = {name: spec[0] for name, spec in self.config.observables.items()}
        return self._condition_and_package(
            x_obs=x_obs,
            n_posterior_samples=n_posterior_samples,
            seed=seed,
            n_reeval=int(settings.get('n_reeval', 500)),
            artifact_path=artifact_path,
            reused=reused,
            rejection_stats=rejection_stats,
            config_hash=config_hash,
            t0=t0,
            progress_cb=_progress,
        )

    def _condition_and_package(
        self,
        x_obs: Dict[str, float],
        n_posterior_samples: int,
        seed: int,
        n_reeval: int,
        artifact_path,
        reused: bool,
        rejection_stats: Optional[Dict[str, Any]],
        config_hash: str,
        t0: float,
        progress_cb: Optional[Callable] = None,
        truncate_bounds: Optional[Dict[str, Tuple[float, float]]] = None,
    ):
        """Steps 2-4 of the SBI pipeline: condition the (already loaded or
        trained) flow on ``x_obs``, recompute derived quantities with the
        MCMC forward model, and package an InferenceResult.

        ``truncate_bounds`` ({param: (lo, hi)} strictly inside the trained
        prior box) applies EXACT uniform-prior truncation by rejection
        filtering of the drawn samples: for uniform priors, restricting the
        prior support and renormalizing is identical to conditioning the
        posterior on the sub-box, so filtering draws is exact (no
        reweighting needed). Oversamples in batches until
        ``n_posterior_samples`` survive (cap 10x); raises if the kept
        fraction falls below 1%.
        """
        from .inference_core import InferenceResult

        torch, sbi_pkg = _import_torch_sbi()

        def _progress(phase: int, n_samples_now: int = 0):
            if progress_cb is not None:
                try:
                    progress_cb(phase, n_samples_now)
                except TypeError:
                    pass

        # --- Step 2: condition on x_obs --------------------------------------
        kept_fraction = None
        if truncate_bounds:
            self._validate_truncation(truncate_bounds)
            idx_map = {name: self.param_names.index(name)
                       for name in truncate_bounds}
            kept = []
            n_drawn = 0
            batch = int(n_posterior_samples)
            max_draws = 10 * int(n_posterior_samples)
            batch_seed = seed
            while sum(len(k) for k in kept) < n_posterior_samples and n_drawn < max_draws:
                draw = self.sample_posterior(x_obs, n_samples=batch, seed=batch_seed)
                n_drawn += len(draw)
                mask = np.ones(len(draw), dtype=bool)
                for name, (lo, hi) in truncate_bounds.items():
                    col = draw[:, idx_map[name]]
                    mask &= (col >= lo) & (col <= hi)
                kept.append(draw[mask])
                batch_seed = (batch_seed or 0) + 1
            samples = np.concatenate(kept, axis=0)
            kept_fraction = float(len(samples) / max(n_drawn, 1))
            if kept_fraction < 0.01:
                raise RuntimeError(
                    f"Prior truncation keeps only {kept_fraction:.2%} of "
                    f"posterior draws ({truncate_bounds}) — the truncated "
                    f"region carries almost no posterior mass. Widen the "
                    f"truncation or use MCMC mode."
                )
            samples = samples[:n_posterior_samples]
        else:
            samples = self.sample_posterior(
                x_obs, n_samples=n_posterior_samples, seed=seed
            )
        n_samples = len(samples)
        log.info(f"Drew {n_samples} posterior samples from the trained flow"
                 + (f" (truncated, kept_fraction={kept_fraction:.3f})"
                    if kept_fraction is not None else ""))
        _progress(2, n_samples)

        # Flow log density at the drawn samples (posterior density estimate,
        # NOT a likelihood — see module docstring). norm_posterior=False:
        # unnormalized w.r.t. prior-box leakage correction (a constant shift
        # per x_obs; rankings are unaffected).
        x_t = torch.as_tensor(self._x_obs_vector(x_obs), dtype=torch.float32)
        theta_t = torch.as_tensor(samples, dtype=torch.float32)
        with torch.no_grad():
            flow_log_prob = self._posterior.log_prob(
                theta_t, x=x_t, norm_posterior=False
            ).detach().cpu().numpy().astype(np.float64)

        # --- Steps 3+4: recompute derived quantities and likelihoods --------
        # Reuse MCMCRunner's forward-model calls and Gaussian likelihood so
        # SBI results are directly comparable to MCMC results (identical
        # physics, conventions, and guard behavior).
        runner = self._get_mcmc_runner()
        from .forward_models import forward_model_k2_flexible
        from .mcmc_runner import _structure_R_body_km

        log.info(f"Recomputing k2/CMR2/thicknesses for {n_samples} posterior samples...")
        k2_results = []
        cmr2_results = []
        D_ocean_results = []
        D_iceIh_results = []
        D_hsphere_results = []
        for i, theta in enumerate(samples):
            theta_dict = runner._expand_theta(theta)
            Re_k2, Im_k2, _, _, _ = forward_model_k2_flexible(
                theta_dict, runner.structure_data,
                return_heating=False, arrhenius_params=runner.arrhenius_params
            )
            k2_results.append((Re_k2, Im_k2))
            # CMR2 must use the same dispatch as the likelihood/reporting fix
            # (2026-07): _compute_model_cmr2 is core-sensitive for v2 configs
            # (sampled core + mass-conservation rho_sil, e.g. Europa 7D) and
            # falls back to the cache scalar for core-blind v1 configs. The
            # previous _get_cache_scalar call here ignored the sampled core,
            # displaying a CMR2 distribution systematically offset from the
            # Gaussian the flow was conditioned on (user-reported 2026-07-13:
            # Europa MoI 'far left of the Gaussian' in the GUI).
            cmr2_results.append(runner._compute_model_cmr2(theta_dict))
            D_ocean_results.append(runner._get_cache_scalar(theta_dict, 'D_ocean_km'))
            D_iceIh_results.append(runner._get_cache_scalar(theta_dict, 'D_iceIh_km'))
            D_hsphere_results.append(runner._get_cache_scalar(theta_dict, 'D_hsphere_km'))
            if (i + 1) % 100 == 0:
                log.info(f"  {i+1}/{n_samples} samples recomputed")
        k2_results = np.array(k2_results)
        cmr2_results = np.array(cmr2_results)
        D_ocean_results = np.array(D_ocean_results)
        D_iceIh_results = np.array(D_iceIh_results)
        D_hsphere_results = np.array(D_hsphere_results)
        _progress(3, n_samples)

        # Heating on a seeded subset (same pattern/settings as MCMCRunner.run).
        n_reeval = min(int(n_reeval), n_samples)
        log.info(f"Recomputing heating for {n_reeval} posterior samples...")
        rng = np.random.RandomState(seed)
        idx_heat = rng.choice(n_samples, n_reeval, replace=False)
        idx_heat.sort()
        heating_results = []
        for si in idx_heat:
            theta_dict = runner._expand_theta(samples[si])
            _, _, _, _, perPhase_W = forward_model_k2_flexible(
                theta_dict, runner.structure_data,
                return_heating=True, arrhenius_params=runner.arrhenius_params
            )
            heating_results.append(perPhase_W if perPhase_W is not None else {})

        # True Gaussian chi^2 log-likelihood per sample, via the exact
        # likelihood the MCMC path samples (includes the no-ocean guard,
        # which returns the -1e30 sentinel for guard-violating draws).
        log.info(f"Evaluating Gaussian log-likelihood for {n_samples} samples...")
        log_likelihoods = np.array(
            [float(runner.log_likelihood_fn(theta)) for theta in samples],
            dtype=np.float64,
        )
        _progress(4, n_samples)

        elapsed = time.time() - t0
        log.info(f"SBI inference complete: {n_samples} samples in {elapsed/60:.1f} min")

        convergence_metrics = {
            'n_samples': int(n_samples),
            'sampler': 'sbi_npe_single_round',
            # No MCMC-style diagnostics apply; SBC/cross-check validation is
            # the Phase-E gate (plan doc, decision 4).
            'ess': float(n_samples),
            'acceptance_rate': None,
            'r_hat': None,
        }

        result = InferenceResult(
            config=self.config,
            samples=samples,
            log_likelihoods=log_likelihoods,
            param_names=self.param_names,
            param_labels=self.param_labels,
            k2_results=k2_results,
            cmr2_results=cmr2_results,
            D_ocean_results=D_ocean_results,
            D_iceIh_results=D_iceIh_results,
            D_hsphere_results=D_hsphere_results,
            heating_results=heating_results,
            convergence_metrics=convergence_metrics,
            metadata={
                'sampler': 'sbi',
                'density_estimator': self._train_info.get('density_estimator'),
                'elapsed_time_s': elapsed,
                'heating_indices': idx_heat,
                'artifact_path': str(artifact_path),
                'artifact_reused': reused,
                'config_hash': config_hash,
                'git_sha': _git_short_sha(),
                'seed': seed,
                'train_seed': self._train_info.get('seed'),
                'n_train_effective': self._train_info.get('n_train_effective'),
                'rejection_stats': rejection_stats,
                'x_obs': x_obs,
                'imag_convention': self.imag_convention,
                # Body radius (constant across the Tb grid) so the GUI can
                # derive mantle thickness = R_body - D_hsphere - R_core.
                'R_body_km': _structure_R_body_km(runner.structure_data),
                # Amortized posterior density at each sample (NOT a likelihood).
                'flow_log_prob': flow_log_prob,
                'sbi_version': sbi_pkg.__version__,
                'torch_version': torch.__version__,
                'truncate_bounds': ({k: [float(lo), float(hi)]
                                     for k, (lo, hi) in truncate_bounds.items()}
                                    if truncate_bounds else None),
                'kept_fraction': kept_fraction,
                'training_obs_noise': (rejection_stats or {}).get('obs_noise'),
            },
            weights=None,
        )
        return result

    def _validate_truncation(
        self, truncate_bounds: Dict[str, Tuple[float, float]]
    ) -> None:
        """Truncation sub-box must name known params and lie inside the
        trained prior box (widening cannot be done post hoc)."""
        lows, highs = self._param_bounds()
        box = dict(zip(self.param_names, zip(lows, highs)))
        for name, (lo, hi) in truncate_bounds.items():
            if name not in box:
                raise ValueError(f"truncate_bounds: unknown parameter '{name}'")
            blo, bhi = box[name]
            if not (blo <= lo < hi <= bhi):
                raise ValueError(
                    f"truncate_bounds for '{name}' = ({lo}, {hi}) must lie "
                    f"strictly inside the trained prior box ({blo}, {bhi}); "
                    f"widening requires retraining."
                )

    def infer_from_artifact(
        self,
        artifact_path,
        x_obs: Optional[Dict[str, float]] = None,
        n_posterior_samples: int = 10000,
        seed: int = 42,
        n_reeval: int = 500,
        truncate_bounds: Optional[Dict[str, Tuple[float, float]]] = None,
        progress_callback: Optional[Callable] = None,
        validated_version_pairs=None,
    ):
        """Amortized inference from a pretrained artifact — NEVER trains.

        Loads the artifact into this runner, validates compatibility with
        ``self.config`` (parameter set, observable set, |Im k2| convention,
        and the trained prior box — priors and observation noise are frozen
        at training time; only observable VALUES are free), conditions the
        flow, and packages the same InferenceResult the MCMC path produces
        (forward-model recompute of k2/CMR2/thicknesses/heating + Gaussian
        log-likelihoods).

        Args:
            artifact_path: Trained .pt artifact.
            x_obs: Observable values to condition on (defaults to
                ``config.observables`` central values). Aliased 'Im_k2' /
                'abs_Im_k2' accepted.
            n_posterior_samples / seed / n_reeval: as in run().
            truncate_bounds: Optional exact uniform-prior truncation, a
                {param: (lo, hi)} sub-box of the trained prior
                (see ``_condition_and_package``).
            progress_callback: Same contract as run().
            validated_version_pairs: See ``_load_artifact_dict``.

        Returns:
            InferenceResult (metadata['mode'] = 'amortized').
        """
        artifact = self._load_artifact_dict(
            artifact_path, validated_version_pairs=validated_version_pairs)

        # Compatibility: the artifact must describe the same inference
        # problem the config poses. Values of observables are free; names,
        # parameter set, convention, and prior box are not.
        art_params = list(artifact['param_names'])
        if art_params != self.param_names:
            raise ValueError(
                f"Artifact parameters {art_params} != config parameters "
                f"{self.param_names}"
            )
        art_obs = list(artifact['obs_names'])
        if art_obs != self.obs_names:
            raise ValueError(
                f"Artifact observables {art_obs} != config observables "
                f"{self.obs_names}"
            )
        if artifact.get('imag_convention') != self.imag_convention:
            raise ValueError(
                f"Artifact imag_convention '{artifact.get('imag_convention')}'"
                f" != '{self.imag_convention}'"
            )
        art_bounds = [tuple(map(float, b)) for b in artifact['param_bounds']]
        lows, highs = self._param_bounds()
        cfg_bounds = list(zip(lows, highs))
        if not np.allclose(np.asarray(art_bounds), np.asarray(cfg_bounds)):
            raise ValueError(
                f"Artifact prior box {art_bounds} != config prior box "
                f"{cfg_bounds}. Priors are frozen at training time; build "
                f"the config from the artifact's metadata (narrow the "
                f"posterior with truncate_bounds instead)."
            )

        self._posterior = artifact['posterior']
        self._train_info = {
            'density_estimator': artifact.get('density_estimator'),
            'seed': artifact.get('seed'),
            'n_train_effective': artifact.get('n_train_effective'),
            'rejection_stats': artifact.get('rejection_stats'),
            'theta_norm': artifact.get('theta_norm'),
            'x_norm': artifact.get('x_norm'),
        }

        if x_obs is None:
            x_obs = {name: spec[0]
                     for name, spec in self.config.observables.items()}

        def _progress(phase: int, n_samples_now: int = 0):
            if progress_callback is not None:
                try:
                    progress_callback({
                        'iteration': phase, 'n_total': 4,
                        'n_samples': n_samples_now,
                    })
                except Exception:
                    pass

        result = self._condition_and_package(
            x_obs={k: float(v) for k, v in x_obs.items()},
            n_posterior_samples=int(n_posterior_samples),
            seed=int(seed),
            n_reeval=int(n_reeval),
            artifact_path=artifact_path,
            reused=True,
            rejection_stats=artifact.get('rejection_stats'),
            config_hash=artifact.get('config_hash', ''),
            t0=time.time(),
            progress_cb=_progress,
            truncate_bounds=truncate_bounds,
        )
        result.metadata['mode'] = 'amortized'
        result.metadata['artifact_created_utc'] = artifact.get('created_utc')
        return result
