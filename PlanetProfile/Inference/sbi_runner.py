class SBIRunner:
    """
    Single-round amortized NPE for interior-structure inference.

    Args:
        config: InferenceConfig with ``mode='sbi'``. ``sampler_settings``
            keys used here:

            - ``num_simulations`` (int, default 10000): training-set size
              requested from the prior (rows lost to rejection reduce the
              effective size, reported in rejection stats).
            - ``density_estimator`` (str, default 'maf'): flow type passed
              to sbi's NPE ('maf' default, 'nsf' optional).
            - ``n_posterior_samples`` (int, default 10000): posterior draws
              returned by ``run()``.
            - ``n_reeval`` (int, default 500): subset size for the heating
              recompute (same meaning as in MCMCRunner).
            - ``sbi_artifact_path`` (str, optional): explicit artifact
              location; otherwise ``sbi_artifacts/`` is scanned for a
              config-hash match and new artifacts are written there.
            - ``phase_stability`` (dict, optional): when
              ``{'enforce': 'no_ocean_Ih', ...}``, the training set is
              generated with the same no-ocean support guard the MCMC
              likelihood applies, so flow support matches MCMC support.

    Example:
        >>> config = InferenceConfig(mode='sbi', bodyname='Titan', ...)
        >>> runner = SBIRunner(config)
        >>> result = runner.run(progress_callback=my_callback)
    """

    def __init__(self, config):
        """Initialize SBI runner. Cheap: no structure cache, no torch/sbi."""
        from .inference_core import InferenceConfig

        if not isinstance(config, InferenceConfig):
            raise TypeError("config must be InferenceConfig instance")
        if config.mode != 'sbi':
            raise ValueError(f"SBIRunner requires config.mode='sbi', got '{config.mode}'")

        self.config = config
        self.param_names = list(config.param_space.keys())
        self.param_labels = self._make_labels(self.param_names)
        self.param_units = self._make_units(self.param_names)
        # x columns follow config.observables key order (same convention
        # as MCMCRunner.generate_sbi_dataset).
        self.obs_names = list(config.observables.keys())
        # All shipped artifacts use |Im k2| (see module docstring).
        self.imag_convention = 'abs'
        # Per-channel Im conventions; populated from obs_names below. Bind_
        # measurement-space channels are 'signed', k2/h2 Im follow
        # imag_convention. Recorded in the artifact by save_artifact.
        self.channel_conventions = self._channel_conventions()

        # Lazily constructed on first use (loads the structure cache).
        self._mcmc_runner = None
        # Populated by train() / load_artifact().
        self._posterior = None
        self._train_info: Dict[str, Any] = {}

    # ------------------------------------------------------------------
    # Metadata helpers
    # ------------------------------------------------------------------

    @staticmethod
    def _make_labels(param_names):
        """LaTeX labels identical to MCMCRunner's (reuses its label map).

        ``MCMCRunner._make_label`` does not touch ``self``, so it is called
        unbound here to avoid constructing a runner (which would load the
        structure cache) just for labels.
        """
        from .mcmc_runner import MCMCRunner
        return [MCMCRunner._make_label(None, name) for name in param_names]

    @staticmethod
    def _make_units(param_names):
        """Physical units per parameter from the registry ('' if none)."""
        from .parameter_registry import PARAMETER_REGISTRY
        units = []
        for name in param_names:
            pdef = PARAMETER_REGISTRY.get(name)
            units.append(pdef.units if (pdef is not None and pdef.units) else '')
        return units

    def _channel_conventions(self) -> Dict[str, str]:
        """Per-observable Im-part convention: 'abs' (folded) or 'signed'.

        The GUI/pre-deploy contract historically assumed every artifact was
        globally ``imag_convention='abs'``. Europa Clipper v2 introduced
        signed-Im ``Bind_`` measurement-space channels alongside the
        abs-folded ``Im_k2``/``Im_h2``. This map makes the per-channel
        convention explicit so a consumer never abs-folds a Bind_ input.

        Bind_ channels are always 'signed'. The k2/h2 imaginary channels
        follow the runner's global ``imag_convention``. Purely-real or
        magnitude channels (Re_k2, CMR2, ...) are omitted (no Im ambiguity).
        """
        conv: Dict[str, str] = {}
        for name in self.obs_names:
            if name.startswith('Bind_'):
                conv[name] = 'signed'
            elif name in ('Im_k2', 'abs_Im_k2', 'Im_h2', 'abs_Im_h2'):
                conv[name] = self.imag_convention
        return conv

    def _param_bounds(self):
        """(low, high) lists in param_names order.

        Supports ``uniform`` and (v5) ``truncated_gaussian`` priors; both are
        bounded, so the box [low, high] is well-defined for each. The
        truncated-Gaussian shape itself is applied in :meth:`build_prior`
        (per-dim torch distribution) — here we only need the support box.
        """
        lows, highs = [], []
        for name in self.param_names:
            spec = self.config.param_space[name]
            prior_type = spec.get('prior_type', 'uniform')
            if prior_type not in ('uniform', 'truncated_gaussian'):
                raise NotImplementedError(
                    f"SBIRunner supports prior_type in {{'uniform', "
                    f"'truncated_gaussian'}} (each maps to an MCMC-matching "
                    f"torch distribution). Parameter '{name}' has "
                    f"prior_type='{prior_type}'. Extend build_prior() with a "
                    f"provably MCMC-matching torch distribution before using it."
                )
            bounds = spec.get('bounds')
            if bounds is None or len(bounds) != 2 or bounds[0] >= bounds[1]:
                raise ValueError(f"Parameter '{name}': missing or invalid bounds {bounds}")
            lows.append(float(bounds[0]))
            highs.append(float(bounds[1]))
        return lows, highs

    def _prior_spec(self) -> Dict[str, Dict[str, Any]]:
        """Serializable prior description stored in the artifact."""
        lows, highs = self._param_bounds()
        spec = {}
        for name, lo, hi in zip(self.param_names, lows, highs):
            pc = self.config.param_space[name]
            if pc.get('prior_type') == 'truncated_gaussian':
                spec[name] = {'prior_type': 'truncated_gaussian',
                              'mean': float(pc['mean']), 'std': float(pc['std']),
                              'bounds': [lo, hi]}
            else:
                spec[name] = {'prior_type': 'uniform', 'bounds': [lo, hi]}
        return spec

    def _get_mcmc_runner(self):
        """Construct (once) the MCMCRunner used for simulation and recompute.

        The MCMC config differs from the SBI config only in ``mode``; the
        parameter space, observables, structure cache, and likelihood are
        shared, which is what guarantees prior/likelihood consistency
        between the two inference modes.
        """
        if self._mcmc_runner is None:
            from .inference_core import InferenceConfig
            from .mcmc_runner import MCMCRunner
            cfg_dict = self.config.to_dict()
            cfg_dict['mode'] = 'mcmc'
            self._mcmc_runner = MCMCRunner(InferenceConfig.from_dict(cfg_dict))
        return self._mcmc_runner

    def _support_guard_active(self) -> bool:
        """True when the config enforces a support cut: the no-ocean
        phase-stability guard and/or one-sided induction bounds (ratified
        2026-07-12; e.g. Europa's |Ae_synodic| > 0.7)."""
        phase_stability = self.config.sampler_settings.get('phase_stability', {}) or {}
        if phase_stability.get('enforce') == 'no_ocean_Ih':
            return True
        return bool(getattr(self.config, 'induction_bounds', {}) or {})

    # ------------------------------------------------------------------
    # Prior
    # ------------------------------------------------------------------

    def build_prior(self):
        """Build a torch prior over the raw theta space from config.param_space.

        - All-``uniform`` param spaces → a single ``BoxUniform`` (unchanged;
          log10_* parameters are already in log space, no transform applied).
        - Any ``truncated_gaussian`` dim (v5 ice-thickness reparameterization)
          → a ``MultipleIndependent`` joint of per-dimension 1-D priors: a
          ``Uniform`` for uniform dims and a truncated-normal for the Gaussian
          dims, built to match MCMCRunner's ``scipy.stats.truncnorm(a, b,
          loc=mean, scale=std)`` EXACTLY (a=(low−mean)/std, b=(high−mean)/std).
          The training thetas are drawn from the MCMC prior, so the SBI prior
          MUST represent the identical density for the flow's leakage
          correction to be unbiased.

        Raises:
            NotImplementedError: for any unsupported prior_type (via
            :meth:`_param_bounds`).
        """
        torch, _ = _import_torch_sbi()
        from sbi.utils.torchutils import BoxUniform

        lows, highs = self._param_bounds()
        prior_types = [self.config.param_space[n].get('prior_type', 'uniform')
                       for n in self.param_names]

        if all(pt == 'uniform' for pt in prior_types):
            return BoxUniform(
                low=torch.as_tensor(lows, dtype=torch.float32),
                high=torch.as_tensor(highs, dtype=torch.float32),
            )

        # Mixed prior: one independent 1-D distribution per dimension.
        from sbi.utils import MultipleIndependent
        from torch.distributions import Uniform
        dists = []
        for name, lo, hi in zip(self.param_names, lows, highs):
            pc = self.config.param_space[name]
            if pc.get('prior_type') == 'truncated_gaussian':
                dists.append(_TruncatedNormal1D(
                    float(pc['mean']), float(pc['std']), lo, hi))
            else:
                dists.append(Uniform(
                    torch.tensor([lo], dtype=torch.float32),
                    torch.tensor([hi], dtype=torch.float32)))
        return MultipleIndependent(dists)

    # ------------------------------------------------------------------
    # Training set
    # ------------------------------------------------------------------

    def generate_training_set(
        self, n_simulations: int, seed: Optional[int] = None,
        obs_noise: bool = True, noise_seed: Optional[int] = None,
    ) -> Tuple[np.ndarray, np.ndarray, Dict[str, Any]]:
        """Generate the (theta, x) training set from the prior.

        Delegates to ``MCMCRunner.generate_sbi_dataset`` with the SBI
        scientific fixes enabled (plan doc, decision 2):

        - ``apply_support_guard=True`` only for configs that enforce the
          no-ocean guard (``sampler_settings['phase_stability']``), so the
          training-set support matches the MCMC posterior support;
        - ``imag_convention='abs'``: x stores |Im k2|;
        - ``drop_nonfinite=True``: TidalPy-failure NaN rows are rejected;
        - ``seed``: reproducible prior draws;
        - ``obs_noise=True`` (default): Gaussian observation noise with the
          config's per-observable sigma is added to x (data = |Im_model| +
          noise, no re-fold — the committed likelihood's generative model).
          Ratified 2026-07-09: REQUIRED for the trained flow to target the
          MCMC posterior; without it NPE learns the singular noiseless
          conditional and fails SBC/crosscheck. Only disable for diagnostics.

        Args:
            n_simulations: Number of prior draws requested. Rows lost to
                the support guard or non-finite outputs are excluded, so
                the returned arrays may have fewer rows.
            seed: Seed for the prior draws (None leaves the global RNG
                state untouched — pass a seed for reproducible datasets).
            obs_noise: Add observation noise to x (see above).
            noise_seed: Dedicated seed for the noise Generator (independent
                of the prior-draw seed).

        Returns:
            (theta, x, stats): theta (n_kept, D), x (n_kept, K) with
            columns in ``self.obs_names`` order, and the rejection-stats
            dict (n_requested, n_rejected_support, n_rejected_nonfinite,
            rejection_rate, imag_convention, seed).
        """
        runner = self._get_mcmc_runner()
        apply_guard = self._support_guard_active()
        theta, x = runner.generate_sbi_dataset(
            n_samples=n_simulations,
            apply_support_guard=apply_guard,
            imag_convention=self.imag_convention,
            drop_nonfinite=True,
            seed=seed,
            obs_noise=obs_noise,
            noise_seed=noise_seed,
        )
        stats = dict(getattr(runner, 'last_sbi_dataset_stats', {}) or {})
        stats.setdefault('n_requested', n_simulations)
        stats['apply_support_guard'] = apply_guard
        stats['n_kept'] = int(len(theta))
        return np.asarray(theta), np.asarray(x), stats

    # ------------------------------------------------------------------
    # Training
    # ------------------------------------------------------------------

    def train(
        self,
        theta: np.ndarray,
        x: np.ndarray,
        seed: Optional[int] = None,
        density_estimator: str = 'maf',
        show_progress_bars: bool = False,
        **train_kwargs,
    ):
        """Train a single-round NPE posterior estimator on (theta, x).

        Uses sbi's ``NPE`` trainer (alias of ``NPE_C``; verified in the
        installed sbi 0.26.1 ``sbi/inference/__init__.py``). Single-round
        training with prior samples uses the plain NLL loss, so the result
        is a fully amortized posterior q(theta | x). The default 'maf'
        density estimator z-scores theta and x internally
        (``posterior_nn`` default ``z_score='independent'``); those
        standardization layers are part of the saved estimator.

        Args:
            theta: (n, D) parameter draws from the prior (raw theta space).
            x: (n, K) simulated observables, columns in ``self.obs_names``
                order, |Im k2| convention. Must be finite.
            seed: torch.manual_seed value for reproducible training
                (None = do not reseed).
            density_estimator: 'maf' (default) or 'nsf'.
            show_progress_bars: Forwarded to the sbi trainer.
            **train_kwargs: Forwarded to ``NPE.train()`` (e.g.
                training_batch_size, stop_after_epochs).

        Returns:
            Trained ``DirectPosterior`` (also stored on ``self._posterior``).
        """
        torch, sbi_pkg = _import_torch_sbi()
        from sbi.inference import NPE

        theta = np.asarray(theta, dtype=np.float64)
        x = np.asarray(x, dtype=np.float64)
        if theta.ndim != 2 or x.ndim != 2 or len(theta) != len(x):
            raise ValueError(
                f"theta and x must be 2-D with equal row counts; "
                f"got theta {theta.shape}, x {x.shape}"
            )
        if theta.shape[1] != len(self.param_names):
            raise ValueError(
                f"theta has {theta.shape[1]} columns but config.param_space "
                f"has {len(self.param_names)} parameters"
            )
        if x.shape[1] != len(self.obs_names):
            raise ValueError(
                f"x has {x.shape[1]} columns but config.observables "
                f"has {len(self.obs_names)} entries"
            )
        if not np.all(np.isfinite(theta)) or not np.all(np.isfinite(x)):
            raise ValueError(
                "Non-finite values in training data. Generate the training "
                "set with drop_nonfinite=True (generate_training_set does)."
            )

        if seed is not None:
            torch.manual_seed(seed)

        prior = self.build_prior()
        theta_t = torch.as_tensor(theta, dtype=torch.float32)
        x_t = torch.as_tensor(x, dtype=torch.float32)

        log.info(
            f"Training NPE ({density_estimator}) on {len(theta)} simulations "
            f"({theta.shape[1]}D theta, {x.shape[1]}D x)..."
        )
        t0 = time.time()
        inference = NPE(
            prior=prior,
            density_estimator=density_estimator,
            show_progress_bars=show_progress_bars,
        )
        inference.append_simulations(theta_t, x_t).train(**train_kwargs)
        posterior = inference.build_posterior()
        elapsed = time.time() - t0
        log.info(f"NPE training complete in {elapsed/60:.1f} min")

        self._posterior = posterior
        # Informational normalization constants (z-scoring itself lives
        # inside the saved estimator; these are recorded for auditability).
        self._train_info.update({
            'density_estimator': density_estimator,
            'seed': seed,
            'n_train_effective': int(len(theta)),
            'theta_norm': {'mean': theta.mean(axis=0).tolist(),
                           'std': theta.std(axis=0).tolist()},
            'x_norm': {'mean': x.mean(axis=0).tolist(),
                       'std': x.std(axis=0).tolist()},
            'train_elapsed_s': elapsed,
        })
        return posterior

